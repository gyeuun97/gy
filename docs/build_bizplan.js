function TBL(headers, rows, widths, o = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (txt, w, isHead, i) => new TableCell({
    width: { size: w, type: WidthType.DXA }, borders, verticalAlign: VerticalAlign.CENTER,
    shading: isHead ? { type: ShadingType.CLEAR, fill: HEAD, color: "auto" }
           : (o.hl && o.hl(i, txt) ? { type: ShadingType.CLEAR, fill: "FFF4E5", color: "auto" } : undefined),
    margins: { top: 60, bottom: 60, left: 90, right: 90 },
    children: [new Paragraph({
      alignment: (isHead || (o.right && o.right.includes(i))) ? (isHead ? AlignmentType.CENTER : AlignmentType.RIGHT) : AlignmentType.LEFT,
      spacing: { before: 0, after: 0 },
      children: [new TextRun({ text: String(txt), font: FONT, size: o.size ?? 18, bold: isHead || (o.boldCol === i), color: INK })],
    })],
  });
  return new Table({
    width: { size: total, type: WidthType.DXA }, columnWidths: widths, layout: TableLayoutType.FIXED,
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, widths[i], true, i)) }),
      ...rows.map(r => new TableRow({ children: r.map((c, i) => cell(c, widths[i], false, i)) })),
    ],
  });
}
